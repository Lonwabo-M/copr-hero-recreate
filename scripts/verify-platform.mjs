// ─── Platform-wide verification from every role's real queries ───────────────
import { AgentClient, summarizeFailures } from "./agent-harness.mjs";

const PASSWORD = "Lasha!Pump2026";

const ops = new AgentClient();
await ops.signUp("agent.ops@lasha.test", PASSWORD, "Lasha Operations");
await ops.mutate("users/testAccess:claimTestAreaAccess", { area: "operations" });

const admin = new AgentClient();
await admin.signUp("agent.admin@lasha.test", PASSWORD, "Lasha Admin");

console.log("\n═══ PLATFORM VERIFICATION ═══\n");

// 1. Deliveries by status.
const all = (await ops.query("deliveries/state_machine:getAllDeliveriesForOps", { limit: 500 })) ?? [];
const byStatus = {};
for (const d of all) byStatus[d.status] = (byStatus[d.status] ?? 0) + 1;
console.log("  deliveries:", JSON.stringify(byStatus), `total=${all.length}`);

// 2. Fleet: profiles, vehicles, trips (post-fix), GPS coverage, availability.
const roster = (await ops.query("users/driverApplications:getDriverRoster", {})) ?? [];
const agentDrivers = roster.filter((r) => /agent\.driver\d+@/.test(r.email ?? ""));
const tripsSum = roster.reduce((s, r) => s + (r.totalTrips ?? 0), 0);
console.log(
  `  roster: ${roster.length} drivers (${agentDrivers.length} agent), available=${roster.filter((r) => r.isAvailable).length}, withVehicle=${roster.filter((r) => r.vehicle).length}, fleet totalTrips=${tripsSum}`
);

// 3. Sample driver earnings after the trips fix.
const d1 = new AgentClient();
await d1.signUp("agent.driver1@lasha.test", PASSWORD, "re-login");
const summary = await d1.query("driver_earnings:getDriverEarningsSummary", {});
console.log(
  `  driver1: payable=${summary?.payableCount} pending=R${((summary?.pendingPayable ?? 0) / 100).toFixed(2)} earnedFromCompleted=R${((summary?.earnedFromCompleted ?? 0) / 100).toFixed(2)}`
);

// 4. Admin: application pipeline.
const approvedApps = await admin.query("users/driverApplications:getApplicationsForReview", { status: "approved" });
console.log(`  applications approved: ${approvedApps?.length ?? 0}`);

// 5. Customer sample: deliveries + business linkage.
const c42 = new AgentClient();
await c42.signUp("agent.customer42@lasha.test", PASSWORD, "re-login");
const status42 = await c42.query("users/onboarding:getOnboardingStatus", {});
const business42 = await c42.query("users/businessProfile:getMyBusiness", {});
const mine42 = await c42.query("deliveries/state_machine:getMyDeliveries", {});
console.log(
  `  customer42: business="${business42?.name ?? "—"}" onboarding=${status42?.complete} myDeliveries=${mine42?.items?.length ?? mine42?.length ?? "?"}`
);

// 6. Notifications generated by real domain events.
const notifs = await c42.query("notifications/service:getMyNotifications", {});
const n = notifs?.items ?? notifs;
console.log(`  customer42 notifications: ${Array.isArray(n) ? n.length : "?"}`);

// 7. Public tracking: milestone completeness on a recent delivered order.
const delivered = all.filter((d) => d.status === "delivered").slice(-3);
for (const d of delivered) {
  const t = await ops.query("deliveries/state_machine:getDeliveryByTracking", {
    trackingNumber: d.trackingNumber,
  });
  const m = t?.milestones ?? {};
  const complete = m.placed && m.pickedUp && m.inTransit && m.delivered;
  console.log(`  track ${d.trackingNumber}: milestones complete=${Boolean(complete)} timeline=${t?.timeline?.length ?? 0}`);
}

// 8. Waybill numbers assigned automatically.
const withWaybill = all.filter((d) => d.waybillNumber).length;
console.log(`  waybills assigned: ${withWaybill}/${all.length}`);

const failures = summarizeFailures("VERIFICATION");
console.log(failures === 0 ? "\nPLATFORM VERIFIED" : `\nVERIFICATION FAILURES: ${failures}`);
process.exit(failures === 0 ? 0 : 1);
